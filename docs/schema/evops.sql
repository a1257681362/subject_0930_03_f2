-- ========================================================================
-- 博物馆文物修复台账 - H2 本地文件数据库初始化脚本
-- 说明：
--   1) 文物编号、项目编号数据库层唯一（含已撤销记录，撤销不抹除）。
--   2) 撤销/作废仅修改状态字段，不删除数据。
--   3) 入藏、借出、归还、修复（阶段结果）、验收均落表，形成完整链路；
--      关键动作另写一条台账流水 t_relic_ledger。
--   4) 本模块不含票务相关表。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 0. 骨架版本表
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('museum-1', '博物馆文物修复台账：文物档案/入藏/修复项目/借还/验收/台账流水');

-- ------------------------------------------------------------------------
-- 1. 文物档案：材质、年代、来源、保存等级
--    status: ACTIVE 在档 / REVOKED 已撤销
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relic_no         VARCHAR(40)  NOT NULL,
    name             VARCHAR(128) NOT NULL,
    category         VARCHAR(64),
    material         VARCHAR(128) NOT NULL,
    era              VARCHAR(64)  NOT NULL,
    source           VARCHAR(255) NOT NULL,
    preservation_grade VARCHAR(16) NOT NULL,
    description      CLOB,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    revoke_reason    VARCHAR(255),
    revoked_at       TIMESTAMP,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_relic_no UNIQUE (relic_no),
    CONSTRAINT ck_relic_status CHECK (status IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT ck_relic_grade CHECK (preservation_grade IN ('ONE', 'TWO', 'THREE'))
);

-- ------------------------------------------------------------------------
-- 2. 入藏登记：一件文物一条入藏记录，关联尺寸与库位
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic_intake (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relic_id         BIGINT NOT NULL,
    intake_no        VARCHAR(40) NOT NULL,
    height_mm        DECIMAL(12,2),
    width_mm         DECIMAL(12,2),
    depth_mm         DECIMAL(12,2),
    weight_g         DECIMAL(12,2),
    location         VARCHAR(128) NOT NULL,
    intake_time      TIMESTAMP NOT NULL,
    receiver         VARCHAR(64),
    condition_note   VARCHAR(500),
    status           VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_intake_relic UNIQUE (relic_id),
    CONSTRAINT uk_intake_no UNIQUE (intake_no),
    CONSTRAINT ck_intake_status CHECK (status IN ('ACTIVE', 'REVOKED'))
);

-- 入藏照片（一张照片一行）
CREATE TABLE IF NOT EXISTS t_relic_photo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intake_id        BIGINT NOT NULL,
    relic_id         BIGINT NOT NULL,
    photo_url        VARCHAR(500) NOT NULL,
    photo_name       VARCHAR(128),
    view_type        VARCHAR(32),
    sort_no          INT NOT NULL DEFAULT 0,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_photo_intake ON t_relic_photo (intake_id);

-- ------------------------------------------------------------------------
-- 3. 修复项目：委托人、方案、阶段结果
--    status: PLANNED 已立项 / REPAIRING 修复中 / REPAIRED 修复完成待验收
--            / ACCEPTED 已验收 / CANCELLED 已作废
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_repair_project (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_no       VARCHAR(40)  NOT NULL,
    relic_id         BIGINT NOT NULL,
    client           VARCHAR(128) NOT NULL,
    client_contact   VARCHAR(64),
    plan             CLOB NOT NULL,
    start_date       DATE,
    expected_end_date DATE,
    finish_date      DATE,
    status           VARCHAR(16) NOT NULL DEFAULT 'PLANNED',
    cancel_reason    VARCHAR(255),
    cancelled_at     TIMESTAMP,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_project_no UNIQUE (project_no),
    CONSTRAINT ck_project_status CHECK (status IN
        ('PLANNED', 'REPAIRING', 'REPAIRED', 'ACCEPTED', 'CANCELLED'))
);
CREATE INDEX IF NOT EXISTS idx_project_relic ON t_repair_project (relic_id);

-- 修复阶段结果（每完成一个阶段登记一行）
CREATE TABLE IF NOT EXISTS t_repair_stage (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL,
    stage_no         INT NOT NULL,
    stage_name       VARCHAR(128) NOT NULL,
    stage_result     CLOB NOT NULL,
    operator         VARCHAR(64),
    recorded_at      TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_stage_project_no UNIQUE (project_id, stage_no)
);

-- ------------------------------------------------------------------------
-- 4. 验收记录：修复完成 -> 验收通过，项目闭环
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_repair_acceptance (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT NOT NULL,
    accepted_by      VARCHAR(64) NOT NULL,
    accepted_at      TIMESTAMP NOT NULL,
    result           VARCHAR(16) NOT NULL,
    opinion          VARCHAR(500),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_acceptance_project UNIQUE (project_id),
    CONSTRAINT ck_acceptance_result CHECK (result IN ('PASS', 'CONDITIONAL'))
);

-- ------------------------------------------------------------------------
-- 5. 借出 / 归还：一条记录贯通一次借还
--    status: LENT 已借出 / RETURNED 已归还 / OVERDUE 逾期（本期不自动流转）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic_loan (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_no          VARCHAR(40) NOT NULL,
    relic_id         BIGINT NOT NULL,
    borrower         VARCHAR(128) NOT NULL,
    purpose          VARCHAR(255),
    lent_at          TIMESTAMP NOT NULL,
    expected_return_at TIMESTAMP,
    returned_at      TIMESTAMP,
    return_condition VARCHAR(255),
    receiver         VARCHAR(64),
    status           VARCHAR(16) NOT NULL DEFAULT 'LENT',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_loan_no UNIQUE (loan_no),
    CONSTRAINT ck_loan_status CHECK (status IN ('LENT', 'RETURNED', 'OVERDUE'))
);
CREATE INDEX IF NOT EXISTS idx_loan_relic ON t_relic_loan (relic_id);

-- ------------------------------------------------------------------------
-- 6. 台账流水：借/还/修/验/入藏/撤销的不可变动作留痕
--    action: INTAKE / LOAN_OUT / RETURN / REPAIR_START / REPAIR_STAGE
--            / REPAIR_FINISH / ACCEPT / REVOKE / CANCEL
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_relic_ledger (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relic_id         BIGINT NOT NULL,
    project_id       BIGINT,
    loan_id          BIGINT,
    action           VARCHAR(24) NOT NULL,
    biz_no           VARCHAR(40),
    summary          VARCHAR(500) NOT NULL,
    occurred_at      TIMESTAMP NOT NULL,
    create_by        BIGINT,
    create_time      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ledger_relic ON t_relic_ledger (relic_id, occurred_at);

-- ------------------------------------------------------------------------
-- 7. 「博物馆文物修复档案起步」幂等锁：保证起步样本全局只播种一次
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_bootstrap_lock (
    id               INT PRIMARY KEY,
    relic_id         BIGINT NOT NULL,
    project_id       BIGINT NOT NULL,
    bootstrapped_at  TIMESTAMP NOT NULL,
    CONSTRAINT ck_bootstrap_singleton CHECK (id = 1)
);
